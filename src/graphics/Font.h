// Returns 35-bit mask for a 5x7 character (5 bits per row, 7 rows)
// Row 0 (top) is in the highest bits we use, Row 6 (bottom) is in the lowest bits.
// Top-to-bottom: Bits 34..30, 29..25, 24..20, 19..15, 14..10, 9..5, 4..0.
