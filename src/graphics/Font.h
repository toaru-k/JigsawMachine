    case 'K': return 0b10001'10010'10100'11000'10100'10010'10001ULL;
    case 'L': return 0b10000'10000'10000'10000'10000'10000'11111ULL;
    case 'M': return 0b10001'11011'10101'10001'10001'10001'10001ULL;
    case 'N': return 0b10001'11001'10101'10011'10001'10001'10001ULL;
    case 'O': return 0b01110'10001'10001'10001'10001'10001'01110ULL;
    case 'P': return 0b11110'10001'10001'11110'10000'10000'10000ULL;
    case 'Q': return 0b01110'10001'10001'10001'10101'10010'01101ULL;
    case 'R': return 0b11110'10001'10001'11110'10100'10010'10001ULL;
    case 'S': return 0b01111'10000'10000'01110'00001'00001'11110ULL;
    case 'T': return 0b11111'00100'00100'00100'00100'00100'00100ULL;
    case 'U': return 0b10001'10001'10001'10001'10001'10001'01110ULL;
    case 'V': return 0b10001'10001'10001'10001'10001'01010'00100ULL;
    case 'W': return 0b10001'10001'10001'10101'10101'11011'10001ULL;
    case 'X': return 0b10001'10001'01010'00100'01010'10001'10001ULL;
    case 'Y': return 0b10001'10001'10001'01010'00100'00100'00100ULL;
    case 'Z': return 0b11111'00001'00010'00100'01000'10000'11111ULL;
    case '0': return 0b01110'10001'10011'10101'11001'10001'01110ULL;
    case '1': return 0b00100'01100'00100'00100'00100'00100'01110ULL;
    case '2': return 0b01110'10001'00001'00110'01000'10000'11111ULL;
    case '3': return 0b01110'10001'00001'00110'00001'10001'01110ULL;
    case '4': return 0b00010'00110'01010'10010'11111'00010'00010ULL;
    case '5': return 0b11111'10000'11110'00001'00001'10001'01110ULL;
    case '6': return 0b01110'10000'10000'11110'10001'10001'01110ULL;
    case '7': return 0b11111'00001'00010'00100'01000'01000'01000ULL;
    case '8': return 0b01110'10001'10001'01110'10001'10001'01110ULL;
    case '9': return 0b01110'10001'10001'01111'00001'00001'01110ULL;
    case 'a': return 0b00000'00000'01110'00001'01111'10001'01111ULL;
    case 'b': return 0b10000'10000'11110'10001'10001'10001'11110ULL;
    case 'c': return 0b00000'00000'01110'10000'10000'10000'01110ULL;
    case 'd': return 0b00001'00001'01111'10001'10001'10001'01111ULL;
    case 'e': return 0b00000'00000'01110'10001'11111'10000'01110ULL;
    case 'f': return 0b00110'01000'11110'01000'01000'01000'01000ULL;
    case 'g': return 0b00000'01111'10001'10001'01111'00001'01110ULL;
    case 'h': return 0b10000'10000'11110'10001'10001'10001'10001ULL;
    case 'i': return 0b00100'00000'00100'00100'00100'00100'00110ULL;
    case 'j': return 0b00010'00000'00010'00010'00010'10010'01100ULL;
    case 'k': return 0b10000'10000'10010'10100'11000'10100'10010ULL;
